#!/usr/bin/env python3
"""Build the translated pages from the English ones and tools/i18n/locales/<lang>.json.

    python tools/i18n/build.py            # write <lang>/index.html, <lang>/useful-links.html, update English pages + sitemap.xml
    python tools/i18n/build.py --check    # change nothing; exit 1 on a stale en.json, missing / stray keys,
                                          # fragments whose tags or {placeholders} differ from English, or stale outputs

For every locale file present (codes: es zh-Hans hi ar fr pt bn ru ja de ko):
  * strings are replaced span-by-span in a copy of the English page, so the markup is untouched;
    a missing key falls back to English and is reported;
  * <html lang>, dir="rtl" for Arabic, canonical, og:url, og:locale for that language;
  * relative asset and page links become absolute (/assets/..., /images/..., /files/..., /<lang>/...);
  * the matching Noto font is appended to the site's font stacks (CJK, Devanagari, Bengali, Arabic only);
  * strings the site's scripts set at run time are passed in as window.I18N.
On every page (English included) build.py maintains four marked blocks:
  <!-- i18n:head -->   hreflang links for every built language + x-default, og:locale:alternate
  <!-- i18n:picker --> the language picker in the sidebar (only when there is more than one language)
  <!-- i18n:note -->   the machine-translation note in the footer (translated pages only)
  <!-- i18n:script --> the picker / suggestion script (only when there is more than one language)
Run it again at any time: the output depends only on the inputs (idempotent).
"""
from __future__ import annotations

import argparse
import html
import json
import re
import sys
from pathlib import Path

import i18nlib as L

GEN_MARK = "<!-- Generated by tools/i18n/build.py from the English page and tools/i18n/locales/{lang}.json. Do not edit; edit those and rebuild. -->"
GEN_RE = re.compile(r"<!-- Generated by tools/i18n/build\.py")
ASSET_V = "3"


# ---------------------------------------------------------------- urls
def page_path(lang, page):
    tail = "" if page == "index.html" else page
    return "/" + tail if lang == "en" else f"/{lang}/{tail}"


def page_url(lang, page):
    return L.BASE_URL + page_path(lang, page)


def rewrite_url(u, lang):
    """A relative URL in an English page -> the URL that works from /<lang>/."""
    if not u or u.startswith(("http:", "https:", "//", "/", "#", "mailto:", "tel:", "data:", "javascript:", "{")):
        return u
    path, sep, frag = u.partition("#")
    if path in ("index.html", ""):
        return f"/{lang}/" + (sep + frag if sep else "")
    if path in L.PAGES:
        return f"/{lang}/{path}" + (sep + frag if sep else "")
    return "/" + u


def rewrite_srcset(v, lang):
    parts = []
    for item in v.split(","):
        item = item.strip()
        if not item:
            continue
        bits = item.split()
        bits[0] = rewrite_url(bits[0], lang)
        parts.append(" ".join(bits))
    return ", ".join(parts)


# ---------------------------------------------------------------- locale files
def load_locale(path: Path):
    raw = L.load_json(path)
    out = {}
    for k, v in raw.items():
        if isinstance(v, dict):
            v = v.get("text")
        out[k] = v
    return out, raw


def check_locale(lang, loc, en):
    problems = []
    missing = [k for k in en if not (isinstance(loc.get(k), str) and loc[k].strip())]
    stray = [k for k in loc if k not in en]
    if missing:
        problems.append(f"{lang}: {len(missing)} missing key(s): " + ", ".join(missing[:8]) + (" ..." if len(missing) > 8 else ""))
    if stray:
        problems.append(f"{lang}: {len(stray)} stray/unknown key(s): " + ", ".join(stray[:8]) + (" ..." if len(stray) > 8 else ""))
    for k, t in loc.items():
        if k not in en or not isinstance(t, str):
            continue
        e = en[k]["text"]
        if L.tag_signature(e) != L.tag_signature(t):
            problems.append(f"{lang}: {k}: tags differ from English")
        if L.placeholders(e) != L.placeholders(t):
            problems.append(f"{lang}: {k}: placeholders differ from English ({L.placeholders(e)} vs {L.placeholders(t)})")
    return problems, missing


# ---------------------------------------------------------------- edits
def apply_edits(src, edits):
    edits = sorted(edits, key=lambda e: e[0])
    for (s1, e1, _), (s2, e2, _) in zip(edits, edits[1:]):
        if s2 < e1:
            raise RuntimeError(f"overlapping edits at {s1}-{e1} and {s2}-{e2}")
    out, pos = [], 0
    for s, e, t in edits:
        out.append(src[pos:s])
        out.append(t)
        pos = e
    out.append(src[pos:])
    return "".join(out)


def each_element(root):
    stack = [root]
    while stack:
        n = stack.pop()
        if n.kind == "el":
            yield n
            if n.tag in ("script", "style", "template"):
                continue
            stack.extend(reversed(n.children))


def esc_attr(t, q='"'):
    t = html.escape(t, quote=False)
    return t.replace(q, "&quot;" if q == '"' else "&#39;")


# ---------------------------------------------------------------- managed blocks
BLOCKS = ("head", "picker", "note", "script")


def set_block(src, name, content, anchor_re, before=True, indent="  "):
    """Replace the content of <!-- i18n:name --> ... <!-- /i18n:name -->, inserting the block on its own line
    before / after the line holding anchor_re if absent. `indent` is the block's indentation."""
    open_m, close_m = f"<!-- i18n:{name} -->", f"<!-- /i18n:{name} -->"
    body = (open_m + "\n" + "".join(indent + ln + "\n" for ln in content) + indent + close_m) if content else (open_m + close_m)
    i = src.find(open_m)
    if i >= 0:
        j = src.index(close_m, i) + len(close_m)
        return src[:i] + body + src[j:]
    m = re.search(anchor_re, src)
    if not m:
        raise RuntimeError(f"no anchor for block {name}: {anchor_re}")
    if before:
        at = src.rfind("\n", 0, m.start()) + 1
    else:
        at = src.find("\n", m.end()) + 1
    return src[:at] + indent + body + "\n" + src[at:]


def native_suggest(T_all, code):
    t = T_all.get(code, {})
    return t.get("ui.suggest") or "", t.get("ui.dismiss") or ""


def font_css(lang):
    fam = L.LANGS[lang][2]
    if not fam:
        return []
    q = fam.replace(" ", "+")
    f = f'"{fam}"'
    return [
        '<link rel="preconnect" href="https://fonts.googleapis.com">',
        '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>',
        f'<link href="https://fonts.googleapis.com/css2?family={q}:wght@300;400;500;600;700&amp;display=swap" rel="stylesheet">',
        '<style>@font-face { font-family: "I18n Latin Serif"; src: local("Liberation Serif"), local("Noto Serif"); unicode-range: U+0000-024F; } '
        f'html[lang="{lang}"] {{ --font-display: "Plate Display", "Plate Display Fallback", "Iowan Old Style", Palatino, Georgia, "I18n Latin Serif", {f}, serif; '
        f'--font-text: "Plate Text", "Plate Text Fallback", Charter, Georgia, "Times New Roman", "I18n Latin Serif", {f}, serif; '
        f'--font-mono: "Plate Mono", ui-monospace, SFMono-Regular, Menlo, {f}, monospace; }}</style>',
    ]


def blocks_for(lang, page, avail, T, T_all, has_og_locale):
    """Content lines for each managed block of `page` in `lang`. T: this language's strings (with English fallback)."""
    multi = len(avail) > 1
    head = [f'<link rel="alternate" hreflang="{c}" href="{page_url(c, page)}">' for c in avail]
    head.append(f'<link rel="alternate" hreflang="x-default" href="{page_url("en", page)}">')
    if not has_og_locale:
        head.append(f'<meta property="og:locale" content="{L.LANGS[lang][1]}">')
    head += [f'<meta property="og:locale:alternate" content="{L.LANGS[c][1]}">' for c in avail if c != lang]
    if multi:
        head.append(f'<link href="/assets/css/i18n.css?v={ASSET_V}" rel="stylesheet">')
    if lang != "en":
        head += font_css(lang)
        js = {k: v for k, v in T.items() if k.startswith("js.")}
        payload = json.dumps(js, ensure_ascii=False, sort_keys=True).replace("</", "<\\/")
        head.append(f"<script>window.I18N = {payload};</script>")

    picker = []
    if multi:
        name = L.LANGS[lang][0]
        label = esc_attr(f'{T["ui.language"]}: {name}')
        picker += [
            '<details class="lang-picker" data-lang-picker>',
            f'  <summary class="motion-toggle lang-toggle" aria-label="{label}"><i class="bi bi-translate" aria-hidden="true"></i><span lang="{lang}">{html.escape(name)}</span></summary>',
            '  <ul class="lang-menu">',
        ]
        for c in avail:
            sug, dis = native_suggest(T_all, c)
            cur = ' aria-current="true"' if c == lang else ""
            rtl = ' dir="rtl"' if L.LANGS[c][3] == "rtl" else ""
            picker.append(f'    <li><a href="{page_path(c, page)}" hreflang="{c}" lang="{c}"{rtl} data-lang="{c}" '
                          f'data-suggest="{esc_attr(sug)}" data-dismiss="{esc_attr(dis)}"{cur}>{html.escape(L.LANGS[c][0])}</a></li>')
        picker += ['  </ul>', '</details>']

    note = []
    if lang != "en":
        msg = T["ui.machine_note"].replace("{en_url}", page_path("en", page))
        note = [f'<p class="i18n-note">{msg}</p>']

    script = [f'<script src="/assets/js/i18n.js?v={ASSET_V}" defer></script>'] if multi else []
    return {"head": head, "picker": picker, "note": note, "script": script}


ANCHORS = {
    "head": (r'<link rel="canonical"[^>]*>', False),
    "picker": (r'<div class="social-links"', True),
    "note": (r'<footer[^>]*>\s*<div class="container">', False),
    "script": (r"</body>", True),
}


def with_blocks(src, blocks):
    for name in BLOCKS:
        anchor, before = ANCHORS[name]
        ind = "      " if name in ("picker", "note") else "  "   # matches the surrounding markup
        src = set_block(src, name, blocks[name], anchor, before=before, indent=ind)
    return src


# ---------------------------------------------------------------- one page in one language
def translate_page(en_src, page, lang, T, text_key):
    occs, _ = L.units_of(en_src, page)
    edits = []
    for o in occs:
        k = text_key.get(o.text)
        if k is None:
            continue
        t = T.get(k)
        if t is None or t == o.text:
            continue
        if o.kind == "text":
            new = t if o.is_html else html.escape(t, quote=False)
        elif o.kind == "attr":
            new = esc_attr(t, o.quote)
        elif o.kind == "title":
            new = html.escape(t, quote=False)
        else:  # jsonld
            new = json.dumps(t, ensure_ascii=False)
        edits.append((o.start, o.end, new))
    src = apply_edits(en_src, edits)

    # second pass: links and per-language head tags
    root = L.parse(src)
    edits = []
    for el in each_element(root):
        for name in ("href", "src", "srcset", "action", "poster"):
            v = el.attr(name)
            if v is None:
                continue
            new = rewrite_srcset(v, lang) if name == "srcset" else rewrite_url(v, lang)
            if el.tag == "link" and el.attr("rel") == "canonical":
                new = page_url(lang, page)
            if new != v:
                sp = L._attr_span(src, el, name)
                edits.append((sp[0], sp[1], new))   # relative URLs here never hold & or quotes
        if el.tag == "meta" and el.attr("property") in ("og:url", "og:locale"):
            sp = L._attr_span(src, el, "content")
            edits.append((sp[0], sp[1], page_url(lang, page) if el.attr("property") == "og:url" else L.LANGS[lang][1]))
        if el.tag == "html":
            raw = src[el.start:el.tag_end]
            dir_attr = ' dir="rtl"' if L.LANGS[lang][3] == "rtl" else ""
            new_raw = re.sub(r'\slang="[^"]*"', f' lang="{lang}"{dir_attr}', raw, count=1)
            edits.append((el.start, el.tag_end, new_raw))
    src = apply_edits(src, edits)
    src = src.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + GEN_MARK.format(lang=lang) + "\n", 1)
    return src


# ---------------------------------------------------------------- sitemap
def build_sitemap(site, avail):
    sm = site / "sitemap.xml"
    meta = {}
    if sm.exists():
        for m in re.finditer(r"<url>(.*?)</url>", sm.read_text(encoding="utf-8"), re.S):
            body = m.group(1)
            loc = re.search(r"<loc>(.*?)</loc>", body).group(1)
            meta[loc] = {t: (re.search(f"<{t}>(.*?)</{t}>", body) or [None, None])[1] for t in ("lastmod", "changefreq", "priority")}
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">']
    for page in L.PAGES:
        en_meta = meta.get(page_url("en", page), {})
        for c in avail:
            mm = meta.get(page_url(c, page)) or en_meta
            out.append("  <url>")
            out.append(f"    <loc>{page_url(c, page)}</loc>")
            for t in ("lastmod", "changefreq", "priority"):
                v = (en_meta.get(t) if t != "priority" or c == "en" else mm.get(t)) or mm.get(t)
                if v:
                    out.append(f"    <{t}>{v}</{t}>")
            for a in avail:
                out.append(f'    <xhtml:link rel="alternate" hreflang="{a}" href="{page_url(a, page)}"/>')
            out.append(f'    <xhtml:link rel="alternate" hreflang="x-default" href="{page_url("en", page)}"/>')
            out.append("  </url>")
    out.append("</urlset>")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- main
def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--site", default=str(L.SITE), help="site root to read and write (default: the repo)")
    ap.add_argument("--locales", default=str(L.LOCALES), help="folder of <lang>.json files (default: tools/i18n/locales)")
    a = ap.parse_args()
    site, locdir = Path(a.site), Path(a.locales)
    problems = []

    en_path = locdir / "en.json"
    if not en_path.exists():
        print("no en.json: run extract.py first")
        return 1
    en = L.load_json(en_path)
    cat, text_key, per_page, _ = L.extract_all(site, en)
    if cat != en:
        problems.append("en.json is stale against the HTML: run extract.py")
    en_text = {k: v["text"] for k, v in en.items()}

    avail = ["en"]
    T_all = {"en": en_text}
    for code in L.LANG_ORDER[1:]:
        p = locdir / f"{code}.json"
        if not p.exists():
            continue
        loc, _ = load_locale(p)
        probs, missing = check_locale(code, loc, en)
        problems += probs
        T = dict(en_text)
        T.update({k: v for k, v in loc.items() if k in en and isinstance(v, str) and v.strip()})
        T_all[code] = T
        avail.append(code)
    for f in locdir.glob("*.json"):
        if f.stem not in L.LANGS:
            problems.append(f"{f.name}: unknown language code (expected one of {', '.join(L.LANG_ORDER)})")

    writes = {}
    for page in L.PAGES:
        src = (site / page).read_text(encoding="utf-8")
        has_og = 'property="og:locale"' in re.sub(r"<!-- i18n:head -->.*?<!-- /i18n:head -->", "", src, flags=re.S)
        en_out = with_blocks(src, blocks_for("en", page, avail, T_all["en"], T_all, has_og))
        writes[site / page] = en_out
        for code in avail[1:]:
            T = T_all[code]
            out = translate_page(en_out, page, code, T, text_key)
            out = with_blocks(out, blocks_for(code, page, avail, T, T_all, has_og))
            writes[site / code / page] = out
    writes[site / "sitemap.xml"] = build_sitemap(site, avail)

    stale_dirs = []
    for code in L.LANG_ORDER[1:]:
        d = site / code
        if code not in avail and d.is_dir():
            for page in L.PAGES:
                f = d / page
                if f.exists() and GEN_RE.search(f.read_text(encoding="utf-8")[:400]):
                    stale_dirs.append(f)

    changed = [p for p, t in writes.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
    if a.check:
        if changed:
            problems.append("outputs are stale (run build.py): " + ", ".join(str(p.relative_to(site)) for p in changed))
        if stale_dirs:
            problems.append("generated pages for a removed locale: " + ", ".join(str(p.relative_to(site)) for p in stale_dirs))
        for p in problems:
            print("FAIL", p)
        print(("check failed" if problems else "check passed") + f": languages {' '.join(avail)}; {len(en)} keys")
        return 1 if problems else 0

    for p in changed:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(writes[p], encoding="utf-8")
    for f in stale_dirs:
        f.unlink()
        try:
            f.parent.rmdir()
        except OSError:
            pass
    for p in problems:
        print("warn", p, "(English used where missing)" if "missing" in p else "")
    print(f"languages: {' '.join(avail)}; {len(en)} keys; wrote {len(changed)} file(s)"
          + (f"; removed {len(stale_dirs)} stale page(s)" if stale_dirs else ""))
    for p in changed:
        print("  ", p.relative_to(site))
    return 0


if __name__ == "__main__":
    sys.exit(main())
